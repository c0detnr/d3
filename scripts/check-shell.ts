import assert from 'node:assert/strict';
import { tr } from '../src/game/i18n/tr.ts';
import { en } from '../src/game/i18n/en.ts';
import { defaults, readSave, writeSave, SAVE_KEY } from '../src/game/core/playerSave.ts';
import { MISSIONS } from '../src/game/core/missions.ts';
import { useShellStore } from '../src/game/core/shellStore.ts';
assert.deepEqual(Object.keys(tr).sort(), Object.keys(en).sort());
for (const value of Object.values(en)) assert.ok(value.length);
assert.equal(MISSIONS.length, 5);
assert.deepEqual(MISSIONS.filter(m => m.playable).map(m => m.id), ['rookie']);
let stored = '';
const storage = { getItem: (key: string) => { assert.equal(key, SAVE_KEY); return stored; }, setItem: (key: string, value: string) => { assert.equal(key, SAVE_KEY); stored = value; } };
const save = defaults(); save.settings.language = 'en'; save.settings.musicVolume = .4; save.missions.rookie = { stars: 2, completed: true };
assert.ok(writeSave(save, storage)); assert.deepEqual(readSave(storage), save);
assert.equal(defaults().settings.tank, '02');
assert.equal(defaults().settings.droneMode, 'ASSIST');
save.settings.tank = '01'; save.settings.droneMode = 'ACRO';
assert.ok(writeSave(save, storage)); assert.deepEqual(readSave(storage), save);
stored = JSON.stringify({ version: 1, settings: { tank: 'invalid', droneMode: 'invalid', language: 'en', volume: .3 }, missions: { rookie: { stars: 2, completed: true } } });
const migrated = readSave(storage);
assert.equal(migrated.settings.tank, '02'); assert.equal(migrated.settings.droneMode, 'ASSIST');
assert.equal(migrated.settings.language, 'en'); assert.equal(migrated.settings.volume, .3); assert.equal(migrated.missions.rookie.stars, 2);
stored = '{'; assert.deepEqual(readSave(storage), defaults());
stored = JSON.stringify({ version: 99 }); assert.deepEqual(readSave(storage), defaults());
stored = JSON.stringify({ version: 1, settings: { sensitivity: -2, volume: 9, musicVolume: -1, language: 'xx' }, missions: { rookie: { stars: 55, completed: true }, unknown: {} } });
const sanitized = readSave(storage); assert.equal(sanitized.settings.sensitivity, .2); assert.equal(sanitized.settings.volume, 1); assert.equal(sanitized.settings.musicVolume, 0); assert.equal(sanitized.settings.language, 'tr'); assert.equal(sanitized.missions.rookie.stars, 3); assert.equal(sanitized.missions.unknown, undefined);
const denied = { getItem() { throw new Error('denied'); }, setItem() { throw new Error('denied'); } };
assert.deepEqual(readSave(denied), defaults()); assert.equal(writeSave(save, denied), false);
const finish = useShellStore.getState().finishMission;
finish({ missionId: 'rookie', victory: true, seconds: 90, shots: 10, hits: 8, stars: 3 });
finish({ missionId: 'rookie', victory: true, seconds: 100, shots: 10, hits: 5, stars: 1 });
assert.equal(useShellStore.getState().progress.rookie.stars, 3);
finish({ missionId: 'rookie', victory: false, seconds: 100, shots: 10, hits: 5, stars: 3 });
assert.equal(useShellStore.getState().result?.stars, 0); assert.equal(useShellStore.getState().progress.rookie.stars, 3);
finish({ missionId: 'supplies', victory: true, seconds: 90, shots: 10, hits: 8, stars: 3 });
assert.equal(useShellStore.getState().progress.supplies, undefined);
console.log('shell: TR/EN keys, five missions, storage roundtrip/denial/corruption/version, result best stars passed');
