import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { loadTankModel } from '../src/game/vehicle/loadTankModel.ts';
import { extractTankRig } from '../src/game/vehicle/tankRig.ts';
import { ThermalView } from '../src/game/effects/ThermalView.ts';
import { pickTankHit } from '../src/game/combat/tankHit.ts';
import { NullEngine, Scene, MeshBuilder, StandardMaterial, DirectionalLight, Vector3, ShadowGenerator, TransformNode, Matrix, PBRMaterial, Mesh, InstancedMesh, FreeCamera, ShaderMaterial, Animation, Quaternion } from '@babylonjs/core';
import { addShadowCasters } from '../src/game/world/createSunShadows.ts';
import { optimizeStaticProps, freezeSceneMaterials } from '../src/game/world/optimizeStaticProps.ts';
import { defaultQuality, hasSavedQuality, readSave } from '../src/game/core/playerSave.ts';

for (const renderer of ['Intel RPL-P', 'Mali', 'Adreno', 'Apple GPU', 'llvmpipe', 'SwiftShader']) assert.equal(defaultQuality(renderer), 'medium');
assert.equal(defaultQuality('NVIDIA GeForce'), 'high');
const storage = { getItem: () => JSON.stringify({ version: 1, settings: { quality: 'low' } }) };
assert.ok(hasSavedQuality(storage));
assert.equal(readSave(storage, 'Intel').settings.quality, 'low');
assert.equal(readSave({ getItem: () => null }, 'Intel').settings.quality, 'medium');
assert.equal(hasSavedQuality({ getItem: () => '{' }), false);
const engine = new NullEngine();
const scene = new Scene(engine);
try {
  const shadows = new ShadowGenerator(1024, new DirectionalLight('sun', new Vector3(-1, -2, 1), scene));
  const material = new StandardMaterial('shared', scene);
  const parts = [0, 3, 6].map(x => {
    const mesh = MeshBuilder.CreateBox(`prop-${x}`, { size: 0.4 }, scene);
    mesh.position.x = x; mesh.material = material; return mesh;
  });
  const animated = MeshBuilder.CreateBox('animated', { size: 2 }, scene);
  animated.material = material;
  const detail = MeshBuilder.CreateBox('TurretArmor_Details_primitive0', { size: 4 }, scene);
  const parent = new TransformNode('anchor', scene);
  const child = MeshBuilder.CreateBox('child', { size: 0.2 }, scene); child.parent = parent;
  const thin = MeshBuilder.CreateBox('thin', { size: 0.4 }, scene);
  thin.material = material; thin.thinInstanceSetBuffer('matrix', Matrix.Identity().asArray(), 16, true);
  const terrain = MeshBuilder.CreateBox('natural-terrain-facets', { size: 2 }, scene);
  const meshes = [...parts, animated, thin, terrain];
  const casters = [...parts];
  const vertices = parts.reduce((sum, mesh) => sum + mesh.getTotalVertices(), 0);
  optimizeStaticProps(meshes, casters, [animated]);
  assert.equal(meshes.length, 4);
  const merged = meshes.find(mesh => mesh.name.endsWith('-batch'))!;
  assert.equal(merged.getTotalVertices(), vertices);
  assert.equal(merged.getBoundingInfo().boundingBox.minimumWorld.x, -0.2);
  assert.ok(Math.abs(merged.getBoundingInfo().boundingBox.maximumWorld.x - 6.2) < 1e-5);
  assert.ok(merged.isWorldMatrixFrozen && merged.doNotSyncBoundingInfo && material.isFrozen);
  assert.equal(animated.isWorldMatrixFrozen, false);
  assert.equal(thin.isWorldMatrixFrozen, false);
  assert.equal(thin.thinInstanceCount, 1);
  assert.equal(terrain.isWorldMatrixFrozen, false);
  addShadowCasters(shadows, [...casters, animated, child, detail]);
  assert.deepEqual(shadows.getShadowMap()!.renderList!.map(mesh => mesh.name), ['animated'], 'Merged small decorations stay below the shadow cutoff');
  addShadowCasters(shadows, [child], 0);
  assert.ok(shadows.getShadowMap()!.renderList!.includes(child), 'Small infantry parts can be explicitly retained');
  const pbr = new PBRMaterial('building', scene);
  const building = new TransformNode('building-placement', scene);
  building.position.set(20, 3, 10); building.rotation.y = .7; building.scaling.x = -1;
  const buildingParts = [0, 4].map(x => {
    const node = new TransformNode(`part-${x}`, scene); node.parent = building; node.position.x = x;
    const mesh = MeshBuilder.CreateBox(`wall-${x}`, { size: 1 }, scene); mesh.parent = node; mesh.material = pbr;
    mesh.metadata = { structure: 'fixture', surface: 'concrete', gltf: { extras: { asset_node_id: `wall-${x}` } } };
    mesh.computeWorldMatrix(true); return mesh;
  });
  const worldVertices = buildingParts.flatMap(mesh => {
    const positions = mesh.getVerticesData('position')!;
    return Array.from({ length: positions.length / 3 }, (_, i) => Vector3.TransformCoordinates(Vector3.FromArray(positions, i * 3), mesh.getWorldMatrix()));
  });
  optimizeStaticProps(buildingParts, []);
  assert.equal(buildingParts.length, 1, 'PBR parts under different static transforms merge');
  const batch = buildingParts[0];
  assert.equal(batch.parent, building, 'Merged geometry retains building ownership');
  for (const point of worldVertices) assert.ok(batch.getBoundingInfo().boundingBox.intersectsPoint(point), 'World-space geometry survives rotated/mirrored parents');
  const pickupRoot = new TransformNode('smoke-placement', scene);
  const pickup = MeshBuilder.CreateBox('loot-test', {}, scene); pickup.parent = pickupRoot; pickup.material = pbr;
  const animatedRoot = new TransformNode('animated-root', scene);
  animatedRoot.animations.push(new Animation('turn', 'rotation.y', 30, Animation.ANIMATIONTYPE_FLOAT));
  const moving = MeshBuilder.CreateBox('moving-child', {}, scene); moving.parent = animatedRoot; moving.material = pbr;
  optimizeStaticProps([pickup, moving], []);
  assert.ok(!pickup.isWorldMatrixFrozen && !moving.isWorldMatrixFrozen, 'Pickups and animated parents stay dynamic');
  const shader = new ShaderMaterial('live-shader', scene, {}, {});
  const hot = new StandardMaterial('thermal-hot', scene);
  const jammer = new StandardMaterial('tank-jammer-lamp', scene);
  const alpha = new StandardMaterial('smoke-supply-marker', scene); alpha.alpha = .65;
  const checkpoint = new StandardMaterial('mission-checkpoint', scene);
  const water = new StandardMaterial('static-water', scene); water.alpha = .72;
  freezeSceneMaterials(scene);
  assert.ok(pbr.isFrozen && material.isFrozen && water.isFrozen);
  assert.ok([shader, hot, jammer, alpha, checkpoint].every(material => !material.isFrozen));
  const camera = new FreeCamera('thermal-check', new Vector3(0, 4, -10), scene);
  const thermal = new ThermalView(scene, camera);
  for (const id of ['01', '02']) {
    const tank = await loadTankModel(scene, new Uint8Array(await readFile(new URL(`../assets/tanks/iron_dust_${id}/iron_dust_${id}.glb`, import.meta.url))), Vector3.Zero());
    const rig = extractTankRig(tank);
    const instances = tank.assets.meshes.filter((mesh): mesh is InstancedMesh => mesh instanceof InstancedMesh);
    assert.ok(instances.length >= 30);
    const renderSources = tank.assets.meshes.filter(mesh => mesh instanceof Mesh && mesh.isVisible && mesh.getTotalVertices()).length;
    assert.ok(renderSources <= 70, `Tank ${id}: ${renderSources} render sources exceed the budget`);
    assert.ok(tank.assets.meshes.every(mesh => !mesh.isDisposed() && !mesh.doNotSyncBoundingInfo));
    const wheel = instances.find(mesh => /RoadWheel/.test(mesh.name) && !/_Details_primitive/i.test(mesh.name)) ?? instances.find(mesh => /RoadWheel/.test(mesh.name))!;
    const before = wheel.computeWorldMatrix(true).clone();
    const joint = rig.wheels.find(w => wheel === w.node || wheel.isDescendantOf(w.node))!;
    joint.node.rotationQuaternion = Quaternion.RotationAxis(Vector3.Right(), .7).multiply(joint.baseRotation);
    assert.ok(!before.equals(wheel.computeWorldMatrix(true)), 'Instanced wheel follows its animated joint');
    addShadowCasters(shadows, tank.assets.meshes, 0);
    assert.ok(shadows.getShadowMap()!.renderList!.includes(wheel), 'Instanced wheels remain shadow casters');
    const indices = wheel.getIndices()!, positions = wheel.getVerticesData('position')!;
    const triangle = Array.from({ length: 3 }, (_, i) => Vector3.TransformCoordinates(Vector3.FromArray(positions, indices[i] * 3), wheel.getWorldMatrix()));
    const target = triangle[0].add(triangle[1]).add(triangle[2]).scale(1 / 3);
    const normal = Vector3.Cross(triangle[1].subtract(triangle[0]), triangle[2].subtract(triangle[0])).normalize().scale(.1);
    const isolated = { tank: { ...tank, assets: { meshes: [wheel] } }, vehicle: { body: {} } } as Parameters<typeof pickTankHit>[1];
    assert.ok(pickTankHit(scene, isolated, target.add(normal), target.subtract(normal)), 'Tank triangle pick hits an instance alone');
    assert.ok(wheel.getWorldMatrix().determinant() * wheel.sourceMesh.computeWorldMatrix(true).determinant() > 0, 'Instance handedness matches source');
    const unregister = thermal.register(tank.assets.meshes);
    thermal.setMode('WHT');
    const mask = scene.customRenderTargets.find(target => target.name === 'thermal-mask')!;
    assert.equal(wheel.sourceMesh.getMaterialForRenderPass(mask.renderPassId)?.name, 'thermal-hot', 'Thermal overrides reach instance source');
    thermal.setMode('DAY'); unregister();
    freezeSceneMaterials(scene);
    assert.ok(tank.assets.meshes.filter(mesh => mesh.material instanceof PBRMaterial).every(mesh => mesh.material!.isFrozen));
    console.log(JSON.stringify({ tank: id, renderSources,
      instances: instances.length, frozenTankMaterials: tank.assets.materials.filter(material => material.isFrozen).length }));
    tank.dispose();
    assert.ok(instances.every(mesh => mesh.isDisposed()));
  }
  thermal.dispose();
  building.dispose(); assert.ok(batch.isDisposed(), 'Building disposal also removes merged mesh');
  console.log('GPU optimization: shadow cutoff, static/PBR world-space batches, pickup/animation exclusion, frozen material exceptions, real tank instances/rig/picking/thermal/disposal and saved quality passed.');
} finally { scene.dispose(); engine.dispose(); }
