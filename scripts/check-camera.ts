import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import HavokPhysics from '@babylonjs/havok';
import { HavokPlugin, MeshBuilder, NullEngine, PhysicsAggregate, PhysicsShapeType, Scene, Vector3 } from '@babylonjs/core';
import { AIM_CAMERA, FollowCamera } from '../src/game/camera/FollowCamera.ts';
import { loadTankModel } from '../src/game/vehicle/loadTankModel.ts';
import { extractTankRig } from '../src/game/vehicle/tankRig.ts';
import { TankVehicle } from '../src/game/vehicle/TankVehicle.ts';
import { TurretController } from '../src/game/vehicle/TurretController.ts';
const bytes = new Uint8Array(await readFile(new URL('../assets/tanks/iron_dust_01/iron_dust_01.glb', import.meta.url)));
const wasmBinary = await readFile(new URL('../node_modules/@babylonjs/havok/lib/esm/HavokPhysics.wasm', import.meta.url));
const havok = await HavokPhysics({ wasmBinary });
const engine = new NullEngine(), scene = new Scene(engine);
scene.enablePhysics(new Vector3(0, -9.81, 0), new HavokPlugin(true, havok)); scene.physicsEnabled = false;
try {
  for (let cycle = 0; cycle < 3; cycle++) {
    const canvas = new EventTarget() as HTMLCanvasElement;
    const tank = await loadTankModel(scene, bytes, Vector3.Zero());
    const vehicle = new TankVehicle(scene, extractTankRig(tank), Vector3.Zero());
    const turret = new TurretController(tank);
    const camera = new FollowCamera(scene, canvas);
    const update = () => camera.update(vehicle, tank.anchor.position, 1 / 60, turret);
    update(); const far = camera.camera.position.clone(), intent = camera.direction.clone();
    assert.equal(intent.y, 0, 'desktop starts with horizontal aim');
    assert.ok(Math.abs(camera.camera.getForwardRay().direction.y + Math.sin(AIM_CAMERA.viewDrop)) < 1e-6,
      'normal view looks below the independent horizontal aim');
    const horizontalTarget = camera.aimTarget(vehicle);
    assert.ok(Math.abs(horizontalTarget.y - far.y) < 1e-6, 'aim ray stays horizontal');
    assert.ok(far.y > vehicle.node.position.y + vehicle.rig.size.y / 2, 'horizontal aim clears the hull');
    for (let i = 0; i < 720; i++) turret.fixedUpdate(horizontalTarget, 1 / 60);
    assert.ok(Math.abs(turret.angles.elevation) < 0.5 * Math.PI / 180, 'horizontal camera aim leaves the gun within half a degree of level');
    turret.reset();
    camera.aiming = true;
    for (let i = 0; i < 180; i++) update();
    assert.ok(camera.camera.position.x > 2.5, 'close camera is to the real +Z bore right');
    assert.ok(Vector3.Distance(camera.camera.position, tank.anchor.position) < 8);
    assert.ok(Vector3.Distance(camera.direction, intent) < 1e-9, 'transition preserves intent');
    const near = camera.camera.position.clone();
    camera.zoom(-2);
    for (let i = 0; i < 60; i++) update();
    assert.ok(camera.camera.fov < 0.5, 'gunner wheel zoom narrows field of view');
    assert.ok(Vector3.Distance(camera.camera.position, near) < 0.001, 'gunner zoom preserves shoulder clearance');
    camera.zoom(-100); update(); assert.ok(camera.camera.fov >= 0.2, 'gunner zoom minimum');
    camera.zoom(100); update(); assert.ok(camera.camera.fov <= 0.7, 'gunner zoom maximum');
    camera.look(100, -30); update();
    assert.ok(Vector3.Dot(camera.camera.getForwardRay().direction, camera.direction) > 0.9999, 'gunner view follows mouse intent while turret lags');
    camera.follow();
    for (let i = 0; i < 300; i++) update();
    assert.ok(Vector3.Distance(camera.camera.position, far) < 0.001, 'original follow distance restored');
    camera.zoom(-2);
    for (let i = 0; i < 180; i++) update();
    assert.ok(Vector3.Distance(camera.camera.position, tank.anchor.position) < Vector3.Distance(far, tank.anchor.position), 'third-person wheel moves camera closer');
    camera.zoom(-100); for (let i = 0; i < 120; i++) update();
    const minimum = camera.camera.position.clone(); camera.zoom(-1); update();
    assert.ok(Vector3.Distance(minimum, camera.camera.position) < 0.001, 'follow radius minimum');
    camera.zoom(100); for (let i = 0; i < 300; i++) update();
    const maximum = camera.camera.position.clone(); camera.zoom(1); update();
    assert.ok(Vector3.Distance(maximum, camera.camera.position) < 0.001, 'follow radius maximum');
    camera.follow(); update();
    camera.impulse(); update(); assert.deepEqual(camera.direction, intent, 'kick never changes aim intent');
    camera.follow(); update();
    const aimWall = MeshBuilder.CreateBox('aim-wall', { width: 30, height: 30, depth: 0.2 }, scene);
    aimWall.position.set(0, 0, 50); aimWall.computeWorldMatrix(true);
    const aimObstacle = new PhysicsAggregate(aimWall, PhysicsShapeType.BOX, { mass: 0 }, scene);
    const aimPoint = camera.aimTarget(vehicle);
    assert.ok(Math.abs(aimPoint.z - 49.9) < 0.01, 'view ray selects the first world obstacle');
    aimObstacle.dispose(); aimWall.dispose();
    assert.ok(Math.abs(Vector3.Distance(camera.camera.position, camera.aimTarget(vehicle)) - 1000) < 1e-6, 'empty view uses a distant target and ignores own hull');
    const touchCamera = new FollowCamera(scene, canvas, true);
    touchCamera.update(vehicle, tank.anchor.position, 1 / 60, turret);
    assert.ok(Vector3.Dot(touchCamera.camera.getForwardRay().direction, touchCamera.direction) > 0.99999,
      'touch normal view keeps its original direction without desktop drop');
    touchCamera.aiming = true;
    for (let i = 0; i < 180; i++) touchCamera.update(vehicle, tank.anchor.position, 1 / 60, turret);
    assert.ok(Vector3.Dot(touchCamera.camera.getForwardRay().direction, turret.getMuzzleRay().direction) > 0.9999, 'touch gunner view still follows the manually aimed bore');
    assert.equal(touchCamera.camera.fov, 0.8, 'touch gunner field of view is unchanged');
    touchCamera.dispose();
    const wall = MeshBuilder.CreateBox('camera-wall', { width: 30, height: 20, depth: 0.2 }, scene);
    wall.position.set(0, 5, -8); wall.computeWorldMatrix(true);
    const obstacle = new PhysicsAggregate(wall, PhysicsShapeType.BOX, { mass: 0 }, scene);
    // New camera boom must stay on the tank side of a thin wall.
    camera.follow(); update(); assert.ok(camera.camera.position.z > -7.6);
    camera.aiming = true; camera.camera.fov = .2; camera.camera.rotation.z = .1;
    camera.resultOrbit(vehicle, tank.anchor.position, 0);
    assert.equal(camera.aiming, false, 'result leaves gunner mode');
    assert.equal(camera.camera.fov, .8, 'result restores exterior field of view');
    assert.equal(camera.camera.rotation.z, 0, 'result removes shot roll');
    assert.ok(Vector3.Distance(camera.camera.position, tank.anchor.position) >= 14, 'blocked result orbit stays outside the hull');
    assert.ok(camera.camera.position.z > -7.6, 'result orbit clears the real Havok wall');
    const resultPosition = camera.camera.position.clone(); update();
    assert.deepEqual(camera.camera.position, resultPosition, 'same-frame follow cannot overwrite result camera');
    camera.resultOrbit(vehicle, tank.anchor.position, .035);
    assert.ok(Vector3.Distance(camera.camera.position, resultPosition) > .1, 'result orbit advances');
    camera.follow(); update();
    const blocked = camera.camera.position.clone(); obstacle.dispose(); wall.dispose(); update();
    assert.ok(camera.camera.position.z < blocked.z && camera.camera.position.z > -10, 'obstruction recovery opens smoothly');
    const crown = MeshBuilder.CreateBox('pine-crowns', { width: 30, height: 20, depth: .2 }, scene);
    crown.position.set(0, 5, -8); crown.computeWorldMatrix(true);
    camera.resultOrbit(vehicle, tank.anchor.position, 0);
    assert.ok(camera.camera.position.z > -7.6, 'result orbit avoids visual foliage without a physics collider');
    assert.ok(Vector3.Distance(camera.camera.position, tank.anchor.position) >= 14, 'foliage avoidance keeps hull clearance');
    crown.dispose(); camera.follow(); update();
    const canopy = MeshBuilder.CreateBox('broadleaf-crowns', { width: 80, depth: 80, height: .2 }, scene);
    canopy.position.y = 4; canopy.computeWorldMatrix(true);
    camera.resultOrbit(vehicle, tank.anchor.position, 0);
    const coveredPosition = camera.camera.position.clone();
    camera.resultOrbit(vehicle, tank.anchor.position, .035);
    assert.ok(Vector3.Distance(camera.camera.position, coveredPosition) > .1, 'orbit continues when the tank is covered from every angle');
    assert.ok(Vector3.Distance(camera.camera.position, tank.anchor.position) >= 14);
    canopy.dispose(); camera.follow(); update();
    camera.look(300, -100); const held = turret.angles; update();
    assert.deepEqual(turret.angles, held, 'camera alone never mutates gun angles');
    camera.overview(); assert.equal(camera.aiming, false);
    camera.dispose(); turret.dispose(); vehicle.dispose(); tank.dispose();
    assert.equal(scene.cameras.length, 0); assert.equal(scene.meshes.length, 0); assert.equal(scene.transformNodes.length, 0);
  }
  console.log('Camera: real GLB shoulder, independent intent, bounded aim/follow zoom, restored follow radius, Havok wall/recovery and 3 disposal cycles passed.');
} finally { scene.dispose(); engine.dispose(); }
